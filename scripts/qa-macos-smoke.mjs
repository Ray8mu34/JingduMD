import { spawn } from 'node:child_process';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
if (process.platform !== 'darwin') throw new Error('This smoke check requires macOS.');
const folder = await mkdtemp(join(tmpdir(), 'jingreader-smoke-'));
const document = join(folder, 'startup.md');
await writeFile(document, '# macOS startup check\n\nA native window must stay open.\n');
const app = spawn(join(process.argv[2], 'Contents/MacOS/jingreader'), [document], { stdio: ['ignore', 'pipe', 'pipe'] });
let output = '';
app.stdout.on('data', chunk => { output += chunk; });
app.stderr.on('data', chunk => { output += chunk; });
let failure;
app.on('error', error => { failure = error; });
await new Promise(resolve => setTimeout(resolve, 10000));
if (failure || app.exitCode !== null || app.signalCode !== null) throw new Error(`Native startup failed: ${failure || app.exitCode}\n${output}`);
app.kill('SIGTERM');
await new Promise(resolve => app.once('exit', resolve));
console.log('Native macOS application starts with a Markdown file and remains running.');
