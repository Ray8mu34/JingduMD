import { createServer } from "vite";
import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";

const server = await createServer({ server: { host: "127.0.0.1", port: 5179 } });
await server.listen();
const browser = await chromium.launch({ executablePath: "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe", headless: true });
const output = join(process.cwd(), "qa-artifacts");
await mkdir(output, { recursive: true });
const assert = (condition, message) => { if (!condition) throw new Error(message); };
try {
  for (const width of [760, 1100]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    await page.goto(`${server.resolvedUrls.local[0]}qa-app.html`);
    await page.locator(".markdown-body h1").waitFor();
    const scroll = page.locator(".reader-scroll");
    await scroll.evaluate((element) => { element.scrollTop = 600; });
    await page.waitForTimeout(100);
    const beforeScroll = await scroll.evaluate((element) => element.scrollTop);
    await page.getByRole("button", { name: "阅读设置" }).click();
    const dialog = page.getByRole("dialog", { name: "阅读设置" });
    await dialog.waitFor();
    assert(await dialog.locator(".quick-row").count() === 5, `${width}: missing quick controls`);
    const dimensions = await dialog.locator(".simple-settings-body").evaluate((element) => ({ scroll: element.scrollHeight, client: element.clientHeight }));
    assert(dimensions.scroll <= dimensions.client + 2, `${width}: quick controls need internal scrolling`);
    assert(await page.evaluate(() => window.__JINGREADER_QA__.fontCalls) === 0, "font list loaded on quick open");
    await scroll.evaluate((element) => { element.scrollTop = 0; });
    await page.screenshot({ path: join(output, `refinement-settings-${width}.png`) });
    await scroll.evaluate((element, top) => { element.scrollTop = top; }, beforeScroll);
    await dialog.getByRole("button", { name: "增大字号" }).click();
    await dialog.getByRole("radio", { name: "舒展", exact: true }).check();
    await dialog.getByRole("radio", { name: "素白" }).check();
    await page.waitForFunction(() => window.__JINGREADER_QA__.saves.at(-1)?.appearance === "white");
    const afterScroll = await scroll.evaluate((element) => element.scrollTop);
    assert(Math.abs(afterScroll - beforeScroll) < 150, `${width}: reading position jumped ${beforeScroll} → ${afterScroll}`);
    await dialog.getByRole("button", { name: "撤销" }).click();
    await page.waitForFunction(() => window.__JINGREADER_QA__.saves.at(-1)?.fontSize === 18.5);
    await dialog.getByRole("button", { name: /详细排版/ }).click();
    assert(await page.getByRole("dialog", { name: "段落与细节" }).count() === 1, "detail page did not replace quick page");
    await page.keyboard.press("Escape");
    assert(await page.getByRole("dialog", { name: "阅读设置" }).count() === 1, "Escape did not return to quick page");
    await dialog.getByRole("button", { name: /详细排版/ }).click();
    await page.getByRole("button", { name: "字体", exact: true }).click();
    await page.waitForFunction(() => window.__JINGREADER_QA__.fontCalls === 1);
    await page.keyboard.press("Escape");
    await page.locator(".reader-scroll > .markdown-body").click({ position: { x: 200, y: 250 } });
    assert(await page.getByRole("dialog", { name: "阅读设置" }).count() === 0, "outside click did not close settings");
    await page.getByRole("button", { name: "阅读设置" }).click();
    await dialog.getByRole("button", { name: "增大字号" }).click();
    await page.waitForFunction(() => window.__JINGREADER_QA__.saves.at(-1)?.fontSize === 19);
    await page.locator(".reader-scroll > .markdown-body").click({ position: { x: 200, y: 250 } });
    await page.getByRole("button", { name: "阅读设置" }).click();
    assert(await dialog.getByRole("spinbutton", { name: "正文字号" }).inputValue() === "19", "close and reopen lost reading size");
    await page.reload();
    await page.locator(".markdown-body h1").waitFor();
    await page.getByRole("button", { name: "阅读设置" }).click();
    assert(await page.getByRole("spinbutton", { name: "正文字号" }).inputValue() === "19", "restart lost reading size");
    await page.evaluate(() => { document.documentElement.style.zoom = "150%"; });
    const lastAction = page.getByRole("button", { name: /详细排版/ });
    await lastAction.scrollIntoViewIfNeeded();
    assert(await lastAction.isVisible(), "display zoom clipped the final quick action");
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  await page.goto(`${server.resolvedUrls.local[0]}qa-app.html?legacy=technical`);
  await page.locator(".markdown-body h1").waitFor();
  await page.getByRole("button", { name: "阅读设置" }).click();
  const dialog = page.getByRole("dialog", { name: "阅读设置" });
  const before = await page.evaluate(() => {
    const app = document.querySelector(".app"), body = document.querySelector(".markdown-body"), heading = body.querySelector("h2");
    return { theme: [...app.classList].find((name) => name.startsWith("theme-")), font: getComputedStyle(body).fontFamily, headingSize: getComputedStyle(heading).fontSize, leading: getComputedStyle(body).lineHeight, imageBrightness: getComputedStyle(document.querySelector(".reader-scroll")).getPropertyValue("--image-brightness") };
  });
  await dialog.getByRole("radio", { name: "静谧夜读" }).check();
  const after = await page.evaluate(() => {
    const app = document.querySelector(".app"), body = document.querySelector(".markdown-body"), heading = body.querySelector("h2");
    return { theme: [...app.classList].find((name) => name.startsWith("theme-")), font: getComputedStyle(body).fontFamily, headingSize: getComputedStyle(heading).fontSize, leading: getComputedStyle(body).lineHeight, imageBrightness: getComputedStyle(document.querySelector(".reader-scroll")).getPropertyValue("--image-brightness"), bg: getComputedStyle(app).backgroundColor, legacy: app.classList.contains("style-legacy") };
  });
  assert(after.legacy && after.theme === before.theme && after.font === before.font && after.headingSize === before.headingSize && after.leading === before.leading && after.imageBrightness === before.imageBrightness, "legacy appearance changed geometry, font, brightness or mode");
  assert(after.bg === "rgb(28, 31, 34)", "legacy appearance did not change paper color");
  await dialog.getByRole("radio", { name: "舒展", exact: true }).check();
  assert(await page.locator(".app.style-legacy.theme-technical").count() === 1, "legacy leading changed typography mode");
  await page.screenshot({ path: join(output, "refinement-legacy-night-1100.png") });
  await page.close();
  const shared = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  await shared.goto(`${server.resolvedUrls.local[0]}qa-app.html`);
  await shared.locator(".markdown-body h1").waitFor();
  await shared.getByRole("button", { name: "阅读设置" }).click();
  await shared.getByRole("radio", { name: "素白" }).check();
  await shared.waitForFunction(() => window.__JINGREADER_QA__.saves.at(-1)?.appearance === "white");
  await shared.evaluate(() => {
    const own = window.__JINGREADER_QA__.saves.at(-1);
    window.__JINGREADER_QA__.emitPreferences({ ...own, appearance: "night", fontSize: 21, remoteImagePolicy: "allow", personalTypographies: [{ id: "another", name: "另一窗口", profile: "reading", overrides: {} }] });
  });
  await shared.getByRole("radio", { name: "静谧夜读" }).waitFor({ state: "visible" });
  await shared.getByRole("button", { name: "增大字号" }).click();
  await shared.waitForFunction(() => window.__JINGREADER_QA__.saves.at(-1)?.fontSize === 21.5);
  await shared.getByRole("button", { name: "撤销" }).click();
  await shared.waitForFunction(() => window.__JINGREADER_QA__.saves.at(-1)?.fontSize === 21);
  const merged = await shared.evaluate(() => window.__JINGREADER_QA__.saves.at(-1));
  assert(merged.appearance === "night" && merged.remoteImagePolicy === "allow" && merged.personalTypographies[0]?.id === "another", "undo overwrote another window's update");
  await shared.close();
  console.log("Full App settings, five quick controls, detail navigation, lazy fonts, undo, anchor and legacy appearance passed.");
} finally { await browser.close(); await server.close(); }
